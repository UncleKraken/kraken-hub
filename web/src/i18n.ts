const dictionaries: Record<Lang, Record<Key, string>> = { en, sq };

let current: Lang = (localStorage.getItem('kh.lang') as Lang | null) ?? 'en';
const listeners = new Set<() => void>();

export function setLang(lang: Lang): void {
  current = lang;
  try {
    localStorage.setItem('kh.lang', lang);
  } catch {
    /* storage may be unavailable */
  }
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

export function getLang(): Lang {
  return current;
}

export function t(key: Key | string, params: Record<string, string | number> = {}): string {
  const dict = dictionaries[current] as Record<string, string>;
  let s = dict[key] ?? (en as Record<string, string>)[key] ?? key;
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s.replace(/\{\w+\}/g, '').trim();
}

/** Re-renders the component when the language changes. */
export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    () => current,
  );
}
